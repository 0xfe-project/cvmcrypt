TEST p384_spki_import(void) {
    CvmEcPoint pt;
    cvmcrypt_ec_init(&pt);
    ASSERT_EQ(EC_OK,
              cvmcrypt_ec_import_spki(&pt, test_p384_spki, sizeof(test_p384_spki)));
    ASSERT_EQ(EC_CURVE_P384, pt.curve);
    ASSERT(!cvmcrypt_mpi_is_zero(&pt.x));
    ASSERT(!cvmcrypt_mpi_is_zero(&pt.y));
    cvmcrypt_ec_free(&pt);
    PASS();
}

TEST p384_verify_valid(void) {
    CvmEcPoint pt;
    cvmcrypt_ec_init(&pt);
    ASSERT_EQ(EC_OK,
              cvmcrypt_ec_import_spki(&pt, test_p384_spki, sizeof(test_p384_spki)));

    bool ok =
        cvmcrypt_ecdsa_verify(&pt, test_p384_hash, sizeof(test_p384_hash), test_p384_r,
                              sizeof(test_p384_r), test_p384_s, sizeof(test_p384_s));
    ASSERT(ok);
    cvmcrypt_ec_free(&pt);
    PASS();
}

TEST p384_verify_tampered(void) {
    CvmEcPoint pt;
    cvmcrypt_ec_init(&pt);
    ASSERT_EQ(EC_OK,
              cvmcrypt_ec_import_spki(&pt, test_p384_spki, sizeof(test_p384_spki)));

    u8 bad_r[48];
    memcpy(bad_r, test_p384_r, 48);
    bad_r[0] ^= 0x01;

    bool ok = cvmcrypt_ecdsa_verify(&pt, test_p384_hash, sizeof(test_p384_hash), bad_r,
                                    sizeof(bad_r), test_p384_s, sizeof(test_p384_s));
    ASSERT(!ok); /* must reject */
    cvmcrypt_ec_free(&pt);
    PASS();
}

SUITE(ecdsa_p384) {
    RUN_TEST(p384_spki_import);
    RUN_TEST(p384_verify_valid);
    RUN_TEST(p384_verify_tampered);
}

